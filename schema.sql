-- SAVI Supabase/PostgreSQL schema

-- One row per bracelet. esp_id is the key everything else refers to and the one
-- the bracelet asks the gateway for, mac is the device's own identity, which the
-- middleware upserts on so a bracelet keeps its row no matter which gateway
-- relays it.
CREATE TABLE IF NOT EXISTS public.braceletes (
    esp_id          INTEGER          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mac             VARCHAR(17)      UNIQUE,
    em_uso          BOOLEAN          NOT NULL DEFAULT TRUE,
    temperatura     REAL,
    bpm             SMALLINT,
    spo2            SMALLINT,
    bateria         SMALLINT         CHECK (bateria BETWEEN 0 AND 100),
    acc_x           REAL,
    acc_y           REAL,
    acc_z           REAL,
    gyro_x          REAL,
    gyro_y          REAL,
    gyro_z          REAL,
    atualizado_em   TIMESTAMPTZ      NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.alertas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    esp_id      INTEGER      NOT NULL REFERENCES public.braceletes (esp_id)
                              ON UPDATE CASCADE ON DELETE RESTRICT,
    tipo        VARCHAR(32)  NOT NULL,
    valor       REAL         NOT NULL,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_alertas_esp_id ON public.alertas (esp_id);
CREATE INDEX IF NOT EXISTS idx_alertas_tipo ON public.alertas (tipo);

-- One row per gateway, written by its own report every minute. is_connected is
-- set by that report and cleared by the broker's last will when the gateway stops
-- answering keepalives, so read it together with atualizado_em. braceletes counts
-- the bracelets streaming to that gateway in the last 90 seconds.
CREATE TABLE IF NOT EXISTS public.gateways (
    gateway_id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mac                 VARCHAR(17)  UNIQUE,
    local               VARCHAR(64),
    bateria             SMALLINT     CHECK (bateria BETWEEN 0 AND 100),
    conectado        BOOLEAN      NOT NULL DEFAULT FALSE,
    braceletes          SMALLINT     NOT NULL DEFAULT 0 CHECK (braceletes >= 0),
    atualizado_em       TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_gateways_conectado ON public.gateways (conectado);

-- Migration for a database created before the bracelet MAC became the identity.
ALTER TABLE public.braceletes ADD COLUMN IF NOT EXISTS mac VARCHAR(17);
ALTER TABLE public.braceletes ADD COLUMN IF NOT EXISTS bateria SMALLINT;
ALTER TABLE public.braceletes ALTER COLUMN em_uso SET DEFAULT TRUE;
ALTER TABLE public.braceletes ALTER COLUMN atualizado_em SET DEFAULT NOW();
CREATE UNIQUE INDEX IF NOT EXISTS braceletes_mac_key ON public.braceletes (mac);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.braceletes'::regclass AND conname = 'braceletes_bateria_check'
    ) THEN
        ALTER TABLE public.braceletes
            ADD CONSTRAINT braceletes_bateria_check CHECK (bateria BETWEEN 0 AND 100);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'braceletes'
          AND column_name = 'esp_id' AND is_identity = 'YES'
    ) THEN
        ALTER TABLE public.braceletes ALTER COLUMN esp_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    -- Rows inserted with an explicit esp_id do not advance the sequence, so push it
    -- past the highest existing ID or the first generated insert collides.
    PERFORM setval(
        pg_get_serial_sequence('public.braceletes', 'esp_id'),
        COALESCE((SELECT MAX(esp_id) FROM public.braceletes), 0) + 1,
        false
    );

    -- Existing rows need a timestamp before the column can be NOT NULL.
    UPDATE public.braceletes SET atualizado_em = NOW() WHERE atualizado_em IS NULL;
    BEGIN
        ALTER TABLE public.braceletes ALTER COLUMN atualizado_em SET NOT NULL;
    EXCEPTION WHEN others THEN
        RAISE NOTICE 'Leaving braceletes.atualizado_em nullable: %', SQLERRM;
    END;
END $$;

